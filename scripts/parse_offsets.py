#!/usr/bin/env python3
"""
Parse IL2CPP Dumper output (dump.cs) and extract offsets for the classes
and fields defined in targets.json. Writes a clean offsets.h header.

Usage:
    python3 parse_offsets.py <dump.cs> <targets.json> <output.h>
"""

import json
import re
import sys
from pathlib import Path


def load_targets(targets_path: str) -> dict:
    with open(targets_path, "r", encoding="utf-8") as f:
        return json.load(f)


def parse_dump(dump_path: str) -> dict:
    """
    Walk the dump.cs and extract field offsets for every class.

    Returns: { "ClassName": { "fieldName": offset_hex_string, ... }, ... }
    """
    if not Path(dump_path).exists():
        raise FileNotFoundError(f"dump.cs not found: {dump_path}")

    with open(dump_path, "r", encoding="utf-8", errors="ignore") as f:
        content = f.read()

    results = {}

    # IL2CPP Dumper format (C# dump):
    #   public class BasePlayer : BaseCombatEntity // 0x?
    #   {
    #       public Vector3 _position; // 0x???
    #       public float _health; // 0x???
    #       ...
    #   }
    #
    # Sometimes the format includes attributes, generics, etc. We handle the
    # common cases.

    class_re = re.compile(
        r"^\s*(?:public\s+)?(?:sealed\s+)?(?:abstract\s+)?"
        r"(?:class|struct)\s+(\w+)",
        re.MULTILINE,
    )

    # Field line:
    #   public Vector3 _position; // 0x1A0
    #   private float _health; // 0x1C
    #   internal System.String _name; // 0x30
    #
    # Also handles:
    #   [CompilerGenerated]
    #   public int <SomeField>k__BackingField; // 0x28
    field_re = re.compile(
        r"^\s*(?:public|private|protected|internal)\s+"
        r"(?:static\s+)?"
        r"(?:readonly\s+)?"
        r"[\w<>\[\]\.\,]+\s+"
        r"([\w<>]+)"
        r"\s*;\s*//\s*(0x[0-9A-Fa-f]+)"
    )

    # Static field line — IL2CPP dumper marks statics differently sometimes:
    #   public static ListHashSet<BaseNetworkable> clientEntities; // 0x???
    static_field_re = re.compile(
        r"^\s*(?:public|private|protected|internal)\s+"
        r"static\s+"
        r"[\w<>\[\]\.\,]+\s+"
        r"([\w<>]+)"
        r"\s*;\s*//\s*(0x[0-9A-Fa-f]+)"
    )

    lines = content.splitlines()
    current_class = None

    for line in lines:
        cm = class_re.search(line)
        if cm:
            current_class = cm.group(1)
            continue

        if current_class is None:
            continue

        fm = field_re.search(line)
        if not fm:
            fm = static_field_re.search(line)

        if fm:
            field_name = fm.group(1)
            offset = fm.group(2)
            results.setdefault(current_class, {})[field_name] = offset

    return results


def write_header(results: dict, targets: dict, out_path: str) -> int:
    """
    Write offsets.h from the parsed results.

    Returns the total number of offsets written.
    """
    lines = [
        "#pragma once",
        "#include <cstdint>",
        "",
        "// Auto-generated by dump_offsets workflow.",
        "// Do not edit manually — changes will be overwritten.",
        "",
        f"// Build: see .last_buildid",
        f"// Generated: {__import__('datetime').datetime.utcnow().isoformat()}Z",
        "",
        "namespace Offsets {",
    ]

    total = 0
    for class_name, class_def in sorted(targets["classes"].items()):
        fields = class_def["fields"]
        parsed = results.get(class_name, {})

        lines.append(f"    // ── {class_name} ──")

        found_any = False
        for field in fields:
            if field in parsed:
                const_name = f"{class_name}_{field.lstrip('_')}"
                lines.append(f"    constexpr uintptr_t {const_name} = {parsed[field]};")
                total += 1
                found_any = True
            else:
                # Comment out missing fields so the header still compiles
                # but the gap is visible.
                const_name = f"{class_name}_{field.lstrip('_')}"
                lines.append(f"    // MISSING: {const_name} (field '{field}' not found in dump)")
                lines.append(f"    // constexpr uintptr_t {const_name} = 0x0;  // MISSING")

        if not found_any:
            lines.append(f"    // WARNING: No fields found for {class_name}")

        lines.append("")

    lines.append("}")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    return total


def main():
    if len(sys.argv) != 4:
        print(f"usage: {sys.argv[0]} <dump.cs> <targets.json> <offsets.h>")
        sys.exit(1)

    dump_path = sys.argv[1]
    targets_path = sys.argv[2]
    out_path = sys.argv[3]

    targets = load_targets(targets_path)
    print(f"[parse] Loaded {len(targets['classes'])} class targets")

    results = parse_dump(dump_path)
    print(f"[parse] Found {len(results)} classes in dump")

    total = write_header(results, targets, out_path)
    print(f"[parse] Wrote {total} offsets to {out_path}")

    if total == 0:
        print("[parse] ERROR: No offsets written. Dump format may have changed.")
        sys.exit(1)


if __name__ == "__main__":
    main()